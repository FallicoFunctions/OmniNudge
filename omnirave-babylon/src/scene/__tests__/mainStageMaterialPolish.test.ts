  describe('mesh-specific overrides', () => {
    it.each(OVERRIDE_EXPECTATIONS)('applies the $key override', ({ key, meshNames, expected }) => {
      const baseMaterial = new PBRMaterial('OverrideProbeBase', scene!);
      baseMaterial.albedoTexture = createProbeTexture();

      const meshes = meshNames.map((name) => {
        const mesh = MeshBuilder.CreateBox(name, { size: 1 }, scene!);
        mesh.material = baseMaterial;
        return mesh;
      });

      const control = MeshBuilder.CreateBox('UnmatchedControlMesh', { size: 1 }, scene!);
      control.material = baseMaterial;

      polishMainStageMaterials([...meshes, control]);

      expect(control.material === baseMaterial).toBe(true);

      const overrideMaterial = meshes[0].material as PBRMaterial;
      for (const mesh of meshes) {
        expect(mesh.material === baseMaterial).toBe(false);
        expect(mesh.material === overrideMaterial).toBe(true);
      }

      expect(overrideMaterial.name).toBe(`OverrideProbeBase__${key}`);
      expect(overrideMaterial.metadata?.mainStageMaterialOverride).toBe(key);
      if (expected.metaPolish === null) {
        expect(overrideMaterial.metadata?.mainStageMaterialPolish).toBeUndefined();
      } else {
        expect(overrideMaterial.metadata?.mainStageMaterialPolish).toBe(expected.metaPolish);
      }

      expect(overrideMaterial.albedoTexture === null).toBe(expected.albedoTextureCleared);
      expect(overrideMaterial.albedoColor.r).toBe(expected.albedoColor[0]);
      expect(overrideMaterial.albedoColor.g).toBe(expected.albedoColor[1]);
      expect(overrideMaterial.albedoColor.b).toBe(expected.albedoColor[2]);
      expect(overrideMaterial.emissiveColor.r).toBe(expected.emissiveColor[0]);
      expect(overrideMaterial.emissiveColor.g).toBe(expected.emissiveColor[1]);
      expect(overrideMaterial.emissiveColor.b).toBe(expected.emissiveColor[2]);
      expect(overrideMaterial.emissiveIntensity).toBe(expected.emissiveIntensity);
      expect(overrideMaterial.metallic).toBe(expected.metallic);
      expect(overrideMaterial.roughness).toBe(expected.roughness);
      expect(overrideMaterial.alpha).toBe(expected.alpha);
      expect(overrideMaterial.transparencyMode).toBe(expected.transparencyMode);
      expect(overrideMaterial.clearCoat.isEnabled).toBe(expected.clearCoatEnabled);
      expect(overrideMaterial.clearCoat.intensity).toBe(expected.clearCoatIntensity);
      expect(overrideMaterial.clearCoat.roughness).toBe(expected.clearCoatRoughness);
      expect(overrideMaterial.environmentIntensity).toBe(expected.environmentIntensity);
      if (expected.zOffset !== undefined) {
        expect(overrideMaterial.zOffset).toBe(expected.zOffset);
      }
    });
  });
